import { readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { defineConfig } from 'tsdown'

const OUT_DIR = '.tmp/test-build'

/**
 * Test-harness build.
 *
 * Every `test/*.test.ts` becomes its own ESM bundle in `.tmp/test-build`, keeping
 * its file name (`turn.test.ts` -> `turn.test.mjs`), so a failing module is easy
 * to point at. Modules imported by more than one test — notably
 * `test/helpers.ts` — are split into a shared chunk by tsdown, so a fixture fix
 * reaches every module at once instead of being copied eight times.
 *
 * `node:*` and every `@deepseek-ai/*` package stay external: the bundles run on
 * plain Node 24 with `node:sqlite`, and must not drag in the DSH host or the
 * vendored packages that only a DSH process provides.
 */
export default defineConfig({
  entry: ['test/*.test.ts'],
  outDir: OUT_DIR,
  format: ['esm'],
  platform: 'node',
  target: 'es2022',
  dts: false,
  clean: true,
  deps: {
    neverBundle: (id) => id.startsWith('node:') || id.startsWith('@deepseek-ai/'),
  },
  /*
   * Node 24 does not expand a directory argument for `node --test`: an argument
   * is a test file or a glob pattern, so a bare directory would be loaded as a
   * script and fail. To keep the documented command —
   * `node --test .tmp/test-build` — working, the build writes the directory's
   * `index.js`, which Node loads as the directory's entry.
   *
   * The bundles are imported one by one, each guarded: a module test that is
   * mid-write (or that imports a host-only package) then fails as its own named
   * test instead of taking the whole run down before any test executes. Every
   * bundle stays individually runnable too:
   * `node --test .tmp/test-build/turn.test.mjs`.
   */
  onSuccess() {
    const outDir = resolve(OUT_DIR)
    const bundles = readdirSync(outDir)
      .filter((name) => name.endsWith('.test.mjs'))
      .sort()
    const source = [
      '// Generated by tsdown.test.config.ts; do not edit.',
      `// Directory entry point so \`node --test ${OUT_DIR}\` runs every bundle.`,
      "import { test } from 'node:test'",
      '',
      'const bundles = [',
      ...bundles.map((name) => `  './${name}',`),
      ']',
      '',
      'for (const bundle of bundles) {',
      '  try {',
      '    await import(bundle)',
      '  } catch (error) {',
      '    // Report a broken bundle as one failing test, keep the rest runnable.',
      '    test(`failed to load ${bundle}`, () => {',
      '      throw error',
      '    })',
      '  }',
      '}',
      '',
    ].join('\n')
    writeFileSync(resolve(outDir, 'index.js'), source, 'utf8')
  },
})
