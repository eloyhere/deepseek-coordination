export const AMP_COPY: Readonly<Record<Locale, Record<string, string>>> = {
  zh,
  en,
  ja: { ...en, ...ja },
  es: { ...en, ...es },
  fr: { ...en, ...fr },
  de: { ...en, ...de },
  ru: { ...en, ...ru },
  pt: { ...en, ...pt },
}

/** Translate one keyset through the active DSH locale (with English fallback). */
export function ampT(locale: string): (key: string) => string {
  const table = AMP_COPY[normaliseLocale(locale)] ?? en
  return (key: string) => table[key] ?? en[key as AmpCopyKey] ?? key
}

/**
 * Resolve a key through the slot locale first, then through this plugin's table.
 * That keeps a partially translated host working: an untranslated key shows the
 * English label instead of the raw identifier.
 */
export function ampTranslate(t: (key: string) => string, locale: string): (key: string) => string {
  const fallback = ampT(locale)
  return (key: string) => {
    const value = t(key)
    return value === key ? fallback(key) : value
  }
}
